import { builtinTemplateMap, type CapabilityName, type DeviceTemplate } from '@voltix/protocol';
import { and, eq } from 'drizzle-orm';
import type { AppContext } from '../../context';
import { deviceTemplates, homeMembers } from '../../db/schema';

/** Built-in template, or a custom template owned by one of the home's owners. */
export async function resolveTemplate(
  ctx: AppContext,
  homeId: string,
  type: string,
): Promise<DeviceTemplate | undefined> {
  const builtin = builtinTemplateMap.get(type);
  if (builtin) return builtin;
  const [row] = await ctx.db
    .select({ t: deviceTemplates })
    .from(deviceTemplates)
    .innerJoin(homeMembers, eq(homeMembers.userId, deviceTemplates.ownerUserId))
    .where(and(eq(homeMembers.homeId, homeId), eq(homeMembers.role, 'owner'), eq(deviceTemplates.key, type)))
    .limit(1);
  if (!row) return undefined;
  return {
    key: row.t.key,
    name: row.t.name,
    icon: row.t.icon,
    capabilities: row.t.capabilities as CapabilityName[],
  };
}

export interface SnippetChannel {
  channel: number;
  type: string;
  relayPin?: number;
  switchPin?: number;
  switchMode?: 'momentary' | 'latching';
}

/** Arduino sketch for the Voltix ESP32 SDK (firmware/lib/Voltix) with the given channel layout. */
export function firmwareSnippet(channels: SnippetChannel[], templates: Map<string, DeviceTemplate>): string {
  const lines = channels.map((c) => {
    const t = templates.get(c.type);
    const relay = c.relayPin !== undefined ? `, ${c.relayPin}` : ', VOLTIX_NO_PIN';
    let s = `  Voltix.addChannel(${c.channel}, "${c.type}"${relay});  // ${t?.name ?? c.type}`;
    if (c.switchPin !== undefined) {
      s += `\n  Voltix.addSwitchInput(${c.channel}, ${c.switchPin}, ${c.switchMode === 'latching' ? 'VOLTIX_LATCHING' : 'VOLTIX_MOMENTARY'});`;
    }
    return s;
  });
  const custom = channels.filter((c) => {
    const caps = templates.get(c.type)?.capabilities ?? [];
    return caps.some((cap) => !['powerState', 'powerLevel'].includes(cap)) || c.relayPin === undefined;
  });
  const handler = custom.length
    ? `
// Called for actions the SDK can't handle with a plain relay (brightness, colour, thermostat, ...).
// Apply the change to your hardware, fill \`response\` with the resulting value and return true.
bool onAction(VoltixChannel &ch, const char *action, JsonObjectConst value, JsonObject response) {
  switch (ch.number) {
${custom.map((c) => `    case ${c.channel}:  // ${templates.get(c.type)?.name ?? c.type}\n      // TODO: drive your hardware here\n      for (JsonPairConst kv : value) response[kv.key()] = kv.value();\n      return true;`).join('\n')}
  }
  return false;
}
`
    : '';
  return `// Generated by Voltix. Board credentials are entered in the setup portal, never in code.
#include <Arduino.h>
#include <Voltix.h>
${handler}
void setup() {
  Serial.begin(115200);
${lines.join('\n')}
${custom.length ? '  Voltix.onAction(onAction);\n' : ''}  Voltix.begin("voltix-esp32", "1.0.0");
}

void loop() {
  Voltix.loop();
}
`;
}
